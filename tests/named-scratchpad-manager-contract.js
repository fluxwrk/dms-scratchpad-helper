const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");

const source = fs.readFileSync("NamedScratchpadDefinitions.js", "utf8").replace(/^\.pragma library\s*/, "");
const context = {};
vm.createContext(context);
vm.runInContext(source, context);

const fields = overrides => ({
    displayName: "Ghostty",
    appId: "org.example.Ghostty",
    title: "",
    launchCommand: "ghostty --class=org.example.Ghostty",
    enabled: true,
    ...overrides
});

let store = context.defaultStore();
const created = context.createDefinition(store, fields(), () => "stable-id");
assert.equal(created.valid, true);
assert.equal(created.definitions.length, 1);
assert.equal(created.definitions[0].id, "stable-id");
store = created.store;

const edited = context.updateDefinition(store, "stable-id", fields({displayName: "Terminal", title: "Scratch"}));
assert.equal(edited.valid, true);
assert.equal(edited.definitions[0].id, "stable-id");
assert.equal(edited.definitions[0].displayName, "Terminal");
store = edited.store;

const second = context.createDefinition(store, fields({displayName: "Music", appId: "music", title: "Player"}), () => "second-id");
assert.equal(second.valid, true);
store = second.store;
const removed = context.deleteDefinition(store, "stable-id");
assert.equal(removed.valid, true);
assert.deepEqual(Array.from(removed.definitions, item => item.id), ["second-id"]);
store = removed.store;

const disabled = context.setDefinitionEnabled(store, "second-id", false);
assert.equal(disabled.valid, true);
assert.equal(disabled.definitions[0].enabled, false);
store = disabled.store;

for (const identity of [
    {appId: "app", title: ""},
    {appId: "", title: "Title"},
    {appId: "app", title: "Title"}
]) assert.equal(context.createDefinition(context.defaultStore(), fields(identity), () => "identity-id").valid, true);
assert.equal(context.createDefinition(context.defaultStore(), fields({appId: "", title: ""}), () => "bad").valid, false);
assert.equal(context.createDefinition(context.defaultStore(), fields({displayName: ""}), () => "bad").valid, false);
assert.equal(context.createDefinition(context.defaultStore(), fields({launchCommand: ""}), () => "bad").valid, false);

let duplicateStore = context.createDefinition(context.defaultStore(), fields(), () => "one").store;
assert.equal(context.createDefinition(duplicateStore, fields({displayName: "Duplicate"}), () => "two").valid, false);

const literalStore = context.createDefinition(context.defaultStore(), fields({appId: "a.b+[x]"}), () => "literal").store;
assert.ok(context.expectedContent(literalStore).content.includes("appid:^a\\.b\\+\\[x\\]$"));
assert.equal(context.expectedContent(store).content.includes("second-id"), false);
const enabled = context.setDefinitionEnabled(store, "second-id", true);
assert.ok(context.expectedContent(enabled.store).content.includes("second-id"));
assert.equal(context.expectedContent(enabled.store).content, context.expectedContent(enabled.store).content);

const headerOnly = context.expectedContent(context.defaultStore());
assert.equal(headerOnly.valid, true);
assert.ok(headerOnly.content.startsWith("# Generated by Scratchpad Helper"));
assert.equal(headerOnly.content.includes("windowrule="), false);

const generated = context.expectedContent(enabled.store).content;
const knownHash = context.contentHash(generated);
assert.equal(context.generatedContentState(enabled.store, generated, knownHash).state, "current");
const changed = context.updateDefinition(enabled.store, "second-id", {displayName: "Changed"});
assert.equal(context.generatedContentState(changed.store, generated, knownHash).state, "pending");
// Reconstruction uses only persisted model/file/hash inputs, not a transient dirty flag.
assert.equal(context.generatedContentState(JSON.parse(JSON.stringify(changed.store)), generated, knownHash).pending, true);
assert.equal(context.generatedContentState(changed.store, generated + "# external\n", knownHash).state, "conflict");
const regenerated = context.expectedContent(changed.store).content;
assert.equal(context.generatedContentState(changed.store, regenerated, context.contentHash(regenerated)).state, "current");

assert.equal(context.loadStore("bad").valid, false);
assert.equal(context.loadStore({schemaVersion: 99, definitions: []}).valid, false);
assert.equal(context.loadStore({schemaVersion: 1, definitions: "bad"}).valid, false);
assert.doesNotThrow(() => context.expectedContent({schemaVersion: 1, definitions: [null, "bad"]}));

const managerQml = fs.readFileSync("NamedScratchpadManager.qml", "utf8");
const configQml = fs.readFileSync("NamedScratchpadConfig.qml", "utf8");
const pickerQml = fs.readFileSync("ScratchpadPicker.qml", "utf8");
const widgetQml = fs.readFileSync("ScratchpadWidget.qml", "utf8");
assert.ok(managerQml.includes("Definitions.createDefinition"));
assert.ok(managerQml.includes("Definitions.updateDefinition"));
assert.ok(managerQml.includes("Definitions.deleteDefinition"));
assert.ok(managerQml.includes("Definitions.setDefinitionEnabled"));
assert.ok(configQml.includes("Definitions.generatedContentState"));
assert.ok(!managerQml.includes(".generate()"));
assert.ok(!managerQml.includes("reloadMango"));
assert.ok(!managerQml.includes("Process"));
assert.ok(!managerQml.includes("launchCommand]") && !managerQml.includes("commandField.text]"));
assert.ok(!pickerQml.includes("toggle_named_scratchpad"));
assert.ok(!widgetQml.includes("toggle_named_scratchpad"));

console.log("named scratchpad manager contract: ok");
